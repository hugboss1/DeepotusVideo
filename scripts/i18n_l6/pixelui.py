from outils import L, S, X, H

F = "js/mod-pixelui.js"
P = "vectorlab.pixel."


def _k(cle):
    return P + cle


def lit(ligne, fr, cle, en, n=1, contexte=False):
    """littéral double-quoté simple"""
    return L(F, ligne, '"' + fr + '"', _k(cle), fr, en, n=n, contexte=contexte)


def titre(ligne, fr, cle, en, src=None, attr="title", contexte=False, pre=" "):
    """attribut title="…" (ou aria-label) dans un gabarit HTML ; `pre` (l'espace, ou le guillemet qui le précède)
    est compris dans l'ancre : la partie fixe du gabarit qui commence là est ainsi couverte"""
    src = fr if src is None else src
    d = (fr, en, "contexte") if contexte else (fr, en)
    return S(F, ligne, f'{pre}{attr}="{src}"', f'{pre}{attr}="${{T("{_k(cle)}")}}"', {_k(cle): d})


def tx(ligne, gauche, fr, droite, cle, en, contexte=False):
    """texte d'un nœud dans un gabarit HTML, ancré par ce qui l'entoure"""
    d = (fr, en, "contexte") if contexte else (fr, en)
    return S(F, ligne, gauche + fr + droite, gauche + f'${{T("{_k(cle)}")}}' + droite, {_k(cle): d})


def attr_js(ligne, prefixe, fr, cle, en, src=None):
    """chaîne JS '…title="…"' passée à num() : devient un gabarit `…title="${T(…)}"`"""
    src = fr.replace("'", "\\'") if src is None else src
    return S(F, ligne, "'" + prefixe + 'title="' + src + '"' + "'",
             "`" + prefixe + f'title="${{T("{_k(cle)}")}}"' + "`", {_k(cle): (fr, en)})


