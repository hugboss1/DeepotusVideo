def G(fichier, ligne, avant, dico):
    """S dont l'`apres` remplace chaque texte français, valeur d'attribut ("…") ou nœud texte (>…<), par ${T(clé)}."""
    apres = avant
    for cle, v in sorted(dico.items(), key=lambda kv: -len(kv[1][0])):
        fr = v[0]
        assert f'"{fr}"' in apres or f">{fr}<" in apres, (fichier, ligne, fr)
        apres = apres.replace(f'"{fr}"', f'"${{T("{cle}")}}"').replace(f">{fr}<", f'>${{T("{cle}")}}<')
    return S(fichier, ligne, avant, apres, dico)


